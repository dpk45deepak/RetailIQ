"""Generate docs/model_evaluation_report.md from the saved metric files. Every number comes from JSON written by the pipeline."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "models"


def md_table(df: pd.DataFrame, fmt: str = "{:.3f}") -> str:
    cols = [df.index.name or ""] + list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [fmt.format(v) if isinstance(v, float) else str(v) for v in row]) + " |")
    return "\n".join(lines)


def main() -> None:
    v = json.loads((M / "value_metrics.json").read_text())
    r = json.loads((M / "recommender_eval.json").read_text())
    meta = json.loads((M / "run_metadata.json").read_text())
    cols = ["accuracy", "precision", "recall", "f1", "roc_auc", "pr_auc"]
    tab = lambda s: pd.DataFrame({n: {c: x[s][c] for c in cols} for n, x in v["models"].items()}).T.rename_axis("model")
    out = [f"# Model evaluation report\n\n*Generated by `scripts/generate_reports.py` from `models/*.json` - do not edit by hand.*\n",
           f"Data source: **{meta.get('data_source', 'n/a')}**.\n",
           "## 1. Customer-value prediction (high-value = top 20% net spend in the next 90 days)\n",
           f"* **Selected model:** {v['selected_model']}\n* **Selection rule:** {v['selection_rule']}\n",
           f"* **Windows:** {json.dumps(v['windows'])}\n* **Sizes:** {json.dumps(v['sizes'])}\n",
           "\n### Validation (used to tune and choose)\n", md_table(tab("validation")),
           "\n### Test (scored once, after the choice was made)\n", md_table(tab("test")),
           "\n### Best hyper-parameters (chosen on validation)\n"]
    for n, x in v["models"].items():
        out.append(f"* **{n}**: `{json.dumps(x['best_params'])}`, decision threshold {x['validation']['threshold']:.3f}, 5-fold CV ROC-AUC on the training period {x['cv_roc_auc_train_mean']:.3f} +/- {x['cv_roc_auc_train_std']:.3f}")
    out += ["\n### Reading the results\n",
            "* Differences between the models are small (see the table). For six-ish tabular features, model choice matters less than feature design and the time-split protocol.",
            "* Precision/recall are reported at a threshold tuned on **validation**, then applied unchanged to test. The positive rate differs per window because the label is a per-window quantile.",
            "* The test window is the Christmas quarter - a distribution shift versus the quieter training window. Test scores therefore measure robustness to seasonality, not only generalisation to new customers.\n",
            "\n## 2. Recommenders (time-aware offline evaluation)\n",
            f"Fit on transactions before **{r['split_date'][:10]}**; evaluated on {r['n_eval_customers']:,} customers against **new** products bought afterwards. Catalogue size at the split: {r['n_train_items']:,}. k = {r['k']}.\n",
            md_table(pd.DataFrame(r["models"]).T.rename_axis("model"), "{:.4f}"),
            f"\nCustomers' actual new purchases sit at popularity percentile **{r['actual_purchase_popularity_percentile']:.2f}**; compare with the `avg_popularity_percentile` column to see which recommenders over-promote best-sellers.\n",
            f"Hybrid weights (from the project brief, not tuned on this test period): `{json.dumps(r['weights'])}`.\n",
            "\n### Limitations\n",
            "* Offline metrics on one split are noisy; confirm with an online A/B test before trusting small differences.",
            "* Only *new*-product purchases count as hits, so absolute precision is low by design.",
            "* Item similarities are pruned/cached per run; results are deterministic given `RANDOM_STATE` but depend on the evaluation sample size."]
    (ROOT / "docs" / "model_evaluation_report.md").write_text("\n".join(out) + "\n")
    print("wrote docs/model_evaluation_report.md")


if __name__ == "__main__":
    main()
